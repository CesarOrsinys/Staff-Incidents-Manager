export class LanguageManager {
  private static currentLang = 'es';

  public static init(): void {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem('SIM_LANG') : null;
    if (saved && translations[saved]) {
      this.currentLang = saved;
    }
    this.applyTranslations();
  }

  public static setLanguage(lang: string): void {
    if (translations[lang]) {
      this.currentLang = lang;
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('SIM_LANG', lang);
      }
      this.applyTranslations();
    }
  }

  public static getLanguage(): string {
    return this.currentLang;
  }

  public static t(key: string, interpolations?: Record<string, string>): string {
    const dict = translations[this.currentLang] || translations['es'];
    let str = dict[key] || translations['es'][key] || key;
    if (interpolations) {
      for (const [k, v] of Object.entries(interpolations)) {
        str = str.replace(`{${k}}`, v);
      }
    }
    return str;
  }

  public static applyTranslations(): void {
    if (typeof document === 'undefined') return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        el.textContent = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (key && el instanceof HTMLInputElement) {
        el.placeholder = this.t(key);
      }
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (key && el instanceof HTMLElement) {
        el.title = this.t(key);
      }
    });
  }
}
